const issue = (id, severity, category, title, description, evidence, fix, guideline, submissionId, reportId) => ({
  id,
  severity,
  category,
  title,
  description,
  evidence,
  suggested_fix: fix,
  guideline_id: guideline,
  submission_id: submissionId,
  report_id: reportId,
})

const report = (id, submissionId, score, summary, issues, actions, createdAt) => ({
  id,
  submission_id: submissionId,
  overall_score: score,
  summary,
  created_at: createdAt,
  issues,
  actions,
})

const action = (id, kind, actor, comment, createdAt) => ({
  id,
  action: kind,
  performed_by: actor,
  comment,
  created_at: createdAt,
})

const submission = (id, title, contentType, status, owner, createdAt, content, reportData, reviewedAt, notes) => ({
  id,
  title,
  content_type: contentType,
  status,
  submitted_by: owner,
  submitted_at: createdAt,
  reviewed_at: reviewedAt ?? null,
  reviewer_notes: notes ?? null,
  content_text: content,
  reports: reportData ? [reportData] : [],
})

